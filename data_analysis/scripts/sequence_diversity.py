# %% [markdown]
# # 8. Aggregated Statistics
#
# Aggregate the per-seed metrics. The reported standard deviations quantify variability across the 10 random seeds.

# %%
aggregate_summary = (
    seed_summary
    .groupby("model")
    .agg(
        n_seeds=("seed", "nunique"),
        mean_hamming_mean=("mean_hamming_mean", "mean"),
        mean_hamming_std=("mean_hamming_mean", "std"),
        nearest_hamming_mean=("nearest_hamming_mean", "mean"),
        nearest_hamming_std=("nearest_hamming_mean", "std"),
        diversity_score_mean=("diversity_score", "mean"),
        diversity_score_std=("diversity_score", "std"),
        weighted_diversity_score_mean=("weighted_diversity_score", "mean"),
        weighted_diversity_score_std=("weighted_diversity_score", "std"),
        n_flagged_natural_mean=("n_flagged_natural", "mean"),
        n_flagged_natural_std=("n_flagged_natural", "std"),
    )
    .reset_index()
    .sort_values("model")
)

print(aggregate_summary)

# %% [markdown]
# # 9. Combined Summary
#
# Combine sample metadata with aggregated distance and diversity metrics for comparison across models.

# %%
sample_metadata_summary = (
    sample_metadata
    .groupby("model")
    .agg(
        total_sequences_in_fasta=("total_sequences_in_fasta", "first"),
        sampled_sequences=("sampled_sequences", "first"),
        sequence_length=("sequence_length", "first"),
    )
    .reset_index()
)

combined_summary = (
    sample_metadata_summary
    .merge(aggregate_summary, on="model")
    .sort_values("model")
    .reset_index(drop=True)
)

print(combined_summary)

