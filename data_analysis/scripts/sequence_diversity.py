# %% [markdown]
# # 3. FASTA Loading and Encoding
#
# Load the natural MSA with `adabmDCA.import_from_fasta`. Generated sequences are sampled with reservoir sampling, then encoded with the same `adabmDCA` protein alphabet.
#
# The natural weights file has one value per filtered natural sequence. The natural FASTA contains one ambiguous `X` residue, so the standard `adabmDCA` protein alphabet and `filter_sequences=True` are used to match the 1,258 weights.

# %%
tokens = get_tokens("protein")
token_to_idx = {token: idx for idx, token in enumerate(tokens)}


def as_numpy_int_array(data) -> np.ndarray:
    """Convert adabmDCA output to a compact integer NumPy array."""
    if isinstance(data, torch.Tensor):
        data = data.detach().cpu().numpy()
    return np.asarray(data, dtype=np.int16)


def iter_fasta_sequences(path: Path) -> Iterable[str]:
    """Yield FASTA sequences as uppercase strings."""
    sequence_parts = []
    with path.open("r") as handle:
        for line in handle:
            line = line.strip()
            if not line:
                continue
            if line.startswith(">"):
                if sequence_parts:
                    yield "".join(sequence_parts).upper()
                    sequence_parts = []
            else:
                sequence_parts.append(line)
        if sequence_parts:
            yield "".join(sequence_parts).upper()


def reservoir_sample_fasta(path: Path, sample_size: int, rng: np.random.Generator) -> Tuple[List[str], int]:
    """Sample FASTA sequences uniformly without loading the full file."""
    sample = []
    n_seen = 0
    for seq in iter_fasta_sequences(path):
        n_seen += 1
        if len(sample) < sample_size:
            sample.append(seq)
            continue
        replace_idx = rng.integers(0, n_seen)
        if replace_idx < sample_size:
            sample[replace_idx] = seq
    return sample, n_seen


def encode_sequences(sequences: List[str], token_to_idx: Dict[str, int]) -> np.ndarray:
    """Encode aligned sequences using the same token indices as adabmDCA."""
    if not sequences:
        raise ValueError("No sequences were provided for encoding.")
    lengths = {len(seq) for seq in sequences}
    if len(lengths) != 1:
        raise ValueError(f"Sequences are not aligned; observed lengths: {sorted(lengths)}")

    encoded = np.empty((len(sequences), len(sequences[0])), dtype=np.int16)
    for i, seq in enumerate(sequences):
        try:
            encoded[i] = [token_to_idx[aa] for aa in seq]
        except KeyError as exc:
            raise ValueError(f"Unsupported token {exc!s} found in sequence {i} from sampled FASTA.") from exc
    return encoded


natural_headers, natural_encoded_raw = import_from_fasta(
    str(natural_fasta),
    tokens=tokens,
    filter_sequences=True,
    remove_duplicates=False,
)
natural_encoded = as_numpy_int_array(natural_encoded_raw)
natural_weights = np.loadtxt(natural_weights_path).astype(np.float64)

n_natural, sequence_length = natural_encoded.shape
if len(natural_weights) != n_natural:
    raise ValueError(
        f"Weights length ({len(natural_weights)}) does not match natural sequences ({n_natural})."
    )

print(f"Loaded {n_natural} natural sequences with alignment length L={sequence_length}.")

# %% [markdown]
# # 4. Hamming Distance Utilities
#
# Compute distances in chunks. For each generated sequence, the notebook stores the average normalized Hamming distance to all natural sequences and the index of its closest natural sequence.

# %%
def hamming_distance_summary(
    query_sequences: np.ndarray,
    reference_sequences: np.ndarray,
    chunk_size: int = DISTANCE_CHUNK_SIZE,
    device: torch.device = DEVICE,
    exclude_self: bool = False,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Return mean distance, nearest distance, and nearest reference index for each query."""
    if query_sequences.shape[1] != reference_sequences.shape[1]:
        raise ValueError(
            f"Alignment lengths differ: query L={query_sequences.shape[1]}, "
            f"reference L={reference_sequences.shape[1]}"
        )
    if exclude_self and len(query_sequences) != len(reference_sequences):
        raise ValueError("exclude_self=True requires query and reference arrays with the same length.")

    reference = torch.as_tensor(reference_sequences, dtype=torch.long, device=device)
    length = reference.shape[1]

    mean_distances = []
    nearest_distances = []
    nearest_indices = []

    for start in tqdm(range(0, len(query_sequences), chunk_size), desc="Hamming chunks"):
        stop = min(start + chunk_size, len(query_sequences))
        query = torch.as_tensor(query_sequences[start:stop], dtype=torch.long, device=device)

        distances = (query[:, None, :] != reference[None, :, :]).sum(dim=2)
        if exclude_self:
            row_idx = torch.arange(stop - start, device=device)
            col_idx = torch.arange(start, stop, device=device)
            distances[row_idx, col_idx] = length + 1
        nearest_distance, nearest_index = distances.min(dim=1)

        mean_distances.append((distances.float().mean(dim=1) / length).detach().cpu().numpy())
        nearest_distances.append((nearest_distance.float() / length).detach().cpu().numpy())
        nearest_indices.append(nearest_index.detach().cpu().numpy())

    return (
        np.concatenate(mean_distances),
        np.concatenate(nearest_distances),
        np.concatenate(nearest_indices),
    )


def compute_diversity_score(
    nearest_natural_indices: np.ndarray,
    n_natural: int,
    rng: np.random.Generator,
    natural_weights: np.ndarray | None = None,
) -> Tuple[float, float, int, np.ndarray]:
    """Flag natural nearest neighbors from N sampled generated sequences."""
    replace = n_natural > len(nearest_natural_indices)
    selected_generated = rng.choice(len(nearest_natural_indices), size=n_natural, replace=replace)

    flagged = np.zeros(n_natural, dtype=bool)
    flagged[nearest_natural_indices[selected_generated]] = True

    diversity_score = flagged.mean()
    weighted_diversity_score = np.nan
    if natural_weights is not None:
        if len(natural_weights) != n_natural:
            raise ValueError("natural_weights must have one value per natural sequence.")
        weighted_diversity_score = natural_weights[flagged].sum() / natural_weights.sum()

    return diversity_score, weighted_diversity_score, flagged.sum(), selected_generated

# %% [markdown]
# # 5. Natural Nearest-Neighbor Baseline
#
# Compute the nearest-neighbor Hamming distance among natural sequences. For each natural sequence, the sequence itself is excluded before selecting the closest natural neighbor.

# %%
_, natural_nearest_distance, natural_nearest_index = hamming_distance_summary(
    natural_encoded,
    natural_encoded,
    exclude_self=True,
)

natural_distance_summary = pd.DataFrame(
    [
        {
            "model": "Natural",
            "nearest_hamming_mean": natural_nearest_distance.mean(),
            "nearest_hamming_std": natural_nearest_distance.std(ddof=1),
        }
    ]
)

print(natural_distance_summary)

# %% [markdown]
# # 6. Seeded Sampling and Metrics
#
# Run the full generated-sequence analysis for 10 random seeds. Each seed draws a fresh sample of 10,000 generated sequences per model, computes nearest-neighbor Hamming distance to the natural MSA, and computes the diversity score.

# %%
seed_metric_rows = []
sample_metadata_rows = []
distance_results_by_seed = {}

for seed in RANDOM_SEEDS:
    print(f"\nSeed {seed}")
    for model_idx, (model_name, fasta_path) in enumerate(generated_fastas.items()):
        sample_rng = np.random.default_rng(seed * 10_000 + model_idx)
        diversity_rng = np.random.default_rng(seed * 10_000 + model_idx + 5_000)

        print(f"  Sampling {model_name} from {fasta_path.relative_to(ROOT)}")
        sampled_sequences, n_seen = reservoir_sample_fasta(fasta_path, SAMPLE_SIZE, sample_rng)
        generated_encoded = encode_sequences(sampled_sequences, token_to_idx)

        if generated_encoded.shape[1] != sequence_length:
            raise ValueError(
                f"{model_name} alignment length is {generated_encoded.shape[1]}, expected {sequence_length}."
            )

        print(f"  Computing distances for {model_name}")
        mean_distance, nearest_distance, nearest_natural_index = hamming_distance_summary(
            generated_encoded,
            natural_encoded,
        )

        diversity_score, weighted_diversity_score, n_flagged, selected_generated = compute_diversity_score(
            nearest_natural_index,
            n_natural=n_natural,
            rng=diversity_rng,
            natural_weights=natural_weights,
        )

        distance_results_by_seed[(seed, model_name)] = {
            "mean_distance_to_natural": mean_distance,
            "nearest_distance_to_natural": nearest_distance,
            "nearest_natural_index": nearest_natural_index,
            "selected_generated_indices": selected_generated,
        }

        sample_metadata_rows.append(
            {
                "seed": seed,
                "model": model_name,
                "total_sequences_in_fasta": n_seen,
                "sampled_sequences": len(generated_encoded),
                "sequence_length": generated_encoded.shape[1],
            }
        )

        seed_metric_rows.append(
            {
                "seed": seed,
                "model": model_name,
                "mean_hamming_mean": mean_distance.mean(),
                "nearest_hamming_mean": nearest_distance.mean(),
                "diversity_score": diversity_score,
                "weighted_diversity_score": weighted_diversity_score,
                "n_flagged_natural": n_flagged,
            }
        )

sample_metadata = pd.DataFrame(sample_metadata_rows)
seed_summary = pd.DataFrame(seed_metric_rows).sort_values(["model", "seed"]).reset_index(drop=True)
print(seed_summary)

# %% [markdown]
